#!/usr/bin/env python3
"""Write the AAPT2 source lists, read from the Android.bp files of the pinned AOSP sources, as a CMake file.

  gen_sources.py SRC_DIR VARIANT OUT.cmake

SRC_DIR holds one directory per AOSP repository (base, core, libbase, logging, ...). VARIANT is "android"
(the device build: Soong targets android, bionic, linux, not_windows) or "host" (host, host_linux, linux,
linux_glibc, glibc, not_windows). For every module below the output defines <cmake name>_SRCS with absolute
paths, so the CMake build follows the upstream lists of the tag instead of a hand-maintained copy.
Files listed in EXCLUDE are left out on purpose; each has its reason next to it, and every exclusion is
also written to the output as a comment.
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bp  # noqa: E402

TARGETS = {
    "android": ["android", "bionic", "linux", "not_windows"],
    "host": ["host", "host_linux", "linux", "linux_glibc", "glibc", "not_windows"],
}

# cmake name, Android.bp (relative to SRC_DIR), module, source directory (relative to SRC_DIR)
MODULES = [
    ("libbase", "libbase/Android.bp", "libbase", "libbase"),
    ("liblog", "logging/liblog/Android.bp", "liblog", "logging/liblog"),
    ("libcutils", "core/libcutils/Android.bp", "libcutils", "core/libcutils"),
    ("libutils", "core/libutils/Android.bp", "libutils", "core/libutils"),
    ("libutils_binder", "core/libutils/binder/Android.bp", "libutils_binder", "core/libutils/binder"),
    ("libziparchive", "libziparchive/Android.bp", "libziparchive", "libziparchive"),
    ("libandroidfw", "base/libs/androidfw/Android.bp", "libandroidfw", "base/libs/androidfw"),
    ("libandroidfw_pathutils", "base/libs/androidfw/Android.bp", "libandroidfw_pathutils", "base/libs/androidfw"),
    ("libincfs_utils", "incremental_delivery/incfs/Android.bp", "libincfs-utils", "incremental_delivery/incfs"),
    ("libincfs", "incremental_delivery/incfs/Android.bp", "libincfs", "incremental_delivery/incfs"),
    ("libbuildversion", "soong/cc/libbuildversion/Android.bp", "libbuildversion", "soong/cc/libbuildversion"),
    ("libaapt2", "base/tools/aapt2/Android.bp", "libaapt2", "base/tools/aapt2"),
    ("aapt2", "base/tools/aapt2/Android.bp", "aapt2", "base/tools/aapt2"),
]

EXCLUDE = {
    # needs libbinder (Parcel); not used by AAPT2
    ("libandroidfw", "CursorWindow.cpp"): "needs libbinder; not used by AAPT2",
    # Android-only backup helpers; need the backup aconfig library and libbinder; not used by AAPT2
    ("libandroidfw", "BackupData.cpp"): "Android-only backup helper, not used by AAPT2",
    ("libandroidfw", "BackupHelpers.cpp"): "Android-only backup helper, not used by AAPT2",
}


def main(src, variant, out):
    targets = TARGETS[variant]
    cache = {}
    lines = ["# generated by gen_sources.py from the Android.bp files in %s (variant %s); do not edit" % (src, variant)]
    for cname, bpfile, module, base in MODULES:
        path = os.path.join(src, bpfile)
        if path not in cache:
            cache[path] = bp.modules(path).mods
        files = bp.resolved([cache[path]], module, targets)
        keep = []
        for f in files:
            if (cname, f) in EXCLUDE:
                lines.append("# excluded from %s: %s (%s)" % (cname, f, EXCLUDE[(cname, f)]))
                continue
            if f.endswith(".proto"):
                continue  # generated separately with protoc
            if "*" in f:
                raise SystemExit("glob in %s %s: %s" % (bpfile, module, f))
            full = os.path.join(src, base, f)
            if not os.path.exists(full):
                raise SystemExit("listed but missing: %s" % full)
            keep.append(full)
        lines.append("set(%s_SRCS" % cname)
        lines += ["    %s" % k for k in keep]
        lines.append(")")
        protos = [os.path.join(src, base, f) for f in files if f.endswith(".proto")]
        if protos:
            lines.append("set(%s_PROTOS" % cname)
            lines += ["    %s" % p for p in protos]
            lines.append(")")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s" % out)


if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]), sys.argv[2], sys.argv[3])
