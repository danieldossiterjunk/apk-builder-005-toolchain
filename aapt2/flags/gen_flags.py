#!/usr/bin/env python3
"""Generate a read-only aconfig C/C++ header from a pinned values file.

  gen_flags.py VALUES_FILE OUT_HEADER

VALUES_FILE lines: "<flag_name> true|false"; the package is the header name without .h, with "_" for ".",
for example android_content_res.h for package android.content.res. The header declares, for every flag,
the C function <package>_<flag>() and the C++ function <package namespace>::<flag>(), both returning the
pinned constant, which is what aconfig's read-only (fixed) code generation gives the code that calls them.
"""
import os, re, sys

values, out = sys.argv[1], sys.argv[2]
base = os.path.basename(out)[:-2]
flags = []
for line in open(values, encoding="utf-8"):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    name, val = line.split()
    if not re.fullmatch(r"[a-z0-9_]+", name) or val not in ("true", "false"):
        raise SystemExit("bad line: %r" % line)
    flags.append((name, val))
ns = base.replace("_", "::")
guard = base.upper() + "_H_PINNED"
lines = ["// generated by gen_flags.py from %s; read-only aconfig flag values" % os.path.basename(values),
         "#ifndef %s" % guard, "#define %s" % guard, "", "#ifdef __cplusplus", "namespace %s {" % ns]
lines += ["inline constexpr bool %s() { return %s; }" % (n, v) for n, v in flags]
lines += ["}  // namespace %s" % ns, 'extern "C" {', "#else", "#include <stdbool.h>", "#endif"]
lines += ["static inline bool %s_%s(void) { return %s; }" % (base, n, v) for n, v in flags]
lines += ["#ifdef __cplusplus", "}", "#endif", "", "#endif"]
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(lines) + "\n")
print("%s: %s" % (out, ", ".join("%s=%s" % f for f in flags)))
